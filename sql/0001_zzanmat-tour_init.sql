    CONSTRAINT `FK_REPORT_POST` FOREIGN KEY (`POST_ID`) REFERENCES `POST` (`POST_ID`) ON DELETE CASCADE,
    INDEX `IDX_REPORT_USER` (`USER_ID`),
    INDEX `IDX_REPORT_POST_STATUS` (`POST_ID`, `REPORT_STATUS`)
) ENGINE=INNODB DEFAULT CHARSET=UTF8MB4 COLLATE=UTF8MB4_UNICODE_CI;

CREATE TABLE `MISSION` (
    `MISSION_ID` BIGINT NOT NULL AUTO_INCREMENT COMMENT '미션 고유 ID',
    `TITLE` VARCHAR(255) NOT NULL COMMENT '미션 제목',
    `DESCRIPTION` TEXT NULL COMMENT '미션 설명',
    `MISSION_TYPE` ENUM('POST', 'COMMENT', 'LIKE', 'CHAT') NOT NULL DEFAULT 'POST' COMMENT '미션 방식',
    `TRIGGER_EVENT` ENUM('CREATE_POST', 'CREATE_COMMENT', 'LIKE', 'OPEN_CHAT') NOT NULL DEFAULT 'CREATE_POST' COMMENT '트리거 이벤트',
    `TARGET_COUNT` INT UNSIGNED NOT NULL DEFAULT 1 COMMENT '목표 횟수',
    `REWARD_POINT` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '보상 포인트',
    `AUTO_COMPLETE` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '자동 완료 여부',
    `PLACE_KEYWORD` VARCHAR(100) NOT NULL DEFAULT '' COMMENT '게시글 장소 포함 키워드',
    `MAX_TOTAL_COST` BIGINT NOT NULL DEFAULT 0 COMMENT '총 경비 상한(원)',
    `START_AT` DATETIME(6) NULL COMMENT '수행 가능 시작 일시',
    `END_AT` DATETIME(6) NULL COMMENT '수행 가능 종료 일시',
    `CREATED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    `UPDATED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (`MISSION_ID`),
    CONSTRAINT `CHK_MISSION_PERIOD` CHECK (`END_AT` IS NULL OR `START_AT` IS NULL OR `END_AT` > `START_AT`),
    INDEX `IDX_MISSION_TRIGGER` (`TRIGGER_EVENT`),
    INDEX `IDX_MISSION_PERIOD` (`START_AT`, `END_AT`)
) ENGINE=INNODB DEFAULT CHARSET=UTF8MB4 COLLATE=UTF8MB4_UNICODE_CI COMMENT='미션 정의 테이블';

CREATE TABLE `MISSION_PROGRESS` (
    `ID` BIGINT NOT NULL AUTO_INCREMENT,
    `USER_ID` BIGINT NOT NULL,
    `MISSION_ID` BIGINT NOT NULL,
    `CURRENT_COUNT` INT UNSIGNED NOT NULL DEFAULT 0,
    `PROGRESS` INT UNSIGNED NOT NULL DEFAULT 0,
    `STATUS` VARCHAR(50) NOT NULL DEFAULT 'IN_PROGRESS' COMMENT '진행 상태',
    `REWARD_RECEIVED` TINYINT(1) NOT NULL DEFAULT 0,
    `COMPLETED_AT` DATETIME(6) NULL,
    `CREATED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    `UPDATED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (`ID`),
    CONSTRAINT `CHK_MISSION_PROGRESS_RATE` CHECK (`PROGRESS` BETWEEN 0 AND 100),
    CONSTRAINT `UK_MISSION_PROGRESS_USER_MISSION` UNIQUE (`USER_ID`, `MISSION_ID`),
    CONSTRAINT `FK_MISSION_PROGRESS_USER` FOREIGN KEY (`USER_ID`) REFERENCES `USER` (`ID`) ON DELETE RESTRICT,
    CONSTRAINT `FK_MISSION_PROGRESS_MISSION` FOREIGN KEY (`MISSION_ID`) REFERENCES `MISSION` (`MISSION_ID`) ON DELETE CASCADE,
    INDEX `IDX_MISSION_PROGRESS_USER_STATUS` (`USER_ID`, `STATUS`)
) ENGINE=INNODB DEFAULT CHARSET=UTF8MB4 COLLATE=UTF8MB4_UNICODE_CI;

CREATE TABLE `POINT_HISTORY` (
    `ID` BIGINT NOT NULL AUTO_INCREMENT,
    `USER_ID` BIGINT NOT NULL,
    `MISSION_ID` BIGINT NULL,
    `POINT` INT NOT NULL,
    `REASON` ENUM('MISSION', 'EVENT', 'ADMIN', 'PURCHASE') NOT NULL,
    `CREATED_AT` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (`ID`),
    CONSTRAINT `FK_POINT_HISTORY_USER` FOREIGN KEY (`USER_ID`) REFERENCES `USER` (`ID`) ON DELETE RESTRICT,
    CONSTRAINT `FK_POINT_HISTORY_MISSION` FOREIGN KEY (`MISSION_ID`) REFERENCES `MISSION` (`MISSION_ID`) ON DELETE SET NULL,
    INDEX `IDX_POINT_HISTORY_USER` (`USER_ID`),
    INDEX `IDX_POINT_HISTORY_MISSION` (`MISSION_ID`)
) ENGINE=INNODB DEFAULT CHARSET=UTF8MB4 COLLATE=UTF8MB4_UNICODE_CI;

CREATE TABLE `SHOP_ITEM` (
    `ITEM_ID` BIGINT NOT NULL AUTO_INCREMENT,
    `NAME` VARCHAR(100) NOT NULL,
    `DESCRIPTION` TEXT NULL,
    `CATEGORY` ENUM('GIFT_CARD', 'TRAVEL', 'FLIGHT', 'TRAIN') NOT NULL,
    `COST_POINT` INT NOT NULL,
    `STOCK` INT NULL COMMENT 'NULL이면 무제한',
