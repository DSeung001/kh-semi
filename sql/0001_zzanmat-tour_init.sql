CREATE TABLE `REPORT` (
    `REPORT_ID` BIGINT NOT NULL AUTO_INCREMENT,
    `USER_ID` BIGINT NOT NULL,
    `POST_ID` BIGINT NOT NULL,
    `REPORT_STATUS` ENUM('PENDING', 'IN_PROGRESS', 'RESOLVED', 'REJECTED') NOT NULL DEFAULT 'PENDING',
