CREATE TABLE `USER` (
    `ID` BIGINT NOT NULL AUTO_INCREMENT COMMENT '회원 PK',
    `USER_ID` VARCHAR(50) NOT NULL COMMENT '로그인 아이디 또는 소셜 식별자',
    `USER_PASSWORD` VARCHAR(255) NULL COMMENT '암호화 비밀번호',
    `EMAIL` VARCHAR(100) NULL COMMENT '이메일',
    `NICKNAME` VARCHAR(50) NOT NULL COMMENT '닉네임',
    `USER_NAME` VARCHAR(30) NULL COMMENT '회원 이름',
    `BIO` VARCHAR(255) NULL COMMENT '자기소개',
    `PROFILE` VARCHAR(500) NULL COMMENT '프로필 이미지 경로',
    `LOGIN_TYPE` ENUM('LOCAL', 'KAKAO', 'NAVER') NOT NULL DEFAULT 'LOCAL' COMMENT '로그인 유형',
    `ROLE` ENUM('USER', 'ADMIN') NOT NULL DEFAULT 'USER' COMMENT '회원 권한',
    `IS_DELETED` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '회원 탈퇴 여부',
    `DELETED_AT` DATETIME NULL COMMENT '회원 탈퇴 일시',
    `LOGIN_SESSION_ID` VARCHAR(100) NULL COMMENT '현재 로그인 세션 식별자',
    `CREATE_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '가입 일시',
    `UPDATE_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '수정 일시',
    PRIMARY KEY (`ID`),
    CONSTRAINT `UK_USER_USER_ID` UNIQUE (`USER_ID`),
    CONSTRAINT `UK_USER_NICKNAME` UNIQUE (`NICKNAME`),
    INDEX `IDX_USER_EMAIL` (`EMAIL`),
    INDEX `IDX_USER_DELETED` (`IS_DELETED`)
) ENGINE=INNODB DEFAULT CHARSET=UTF8MB4 COLLATE=UTF8MB4_UNICODE_CI COMMENT='회원 정보';

CREATE TABLE `POST` (
    `POST_ID` BIGINT NOT NULL AUTO_INCREMENT COMMENT '게시글 PK',
    `USER_ID` BIGINT NOT NULL COMMENT '작성 회원 PK',
    `TITLE` VARCHAR(200) NOT NULL COMMENT '게시글 제목',
    `CONTENT` TEXT NOT NULL COMMENT '게시글 내용',
    `PLACE` VARCHAR(100) NULL COMMENT '여행 장소',
    `VIEW_COUNT` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '조회 수',
    `IS_BLOCK` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '삭제 또는 차단 여부',
    `IS_USER_WITHDRAWN` TINYINT(1) NOT NULL DEFAULT 0 COMMENT '작성자 탈퇴 비노출 여부',
    `TRANSPORT_COST` BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '교통비',
    `FOOD_COST` BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '식비',
    `OTHER_COST` BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '기타 비용',
    `CREATE_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '작성 일시',
    `UPDATE_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '수정 일시',
    PRIMARY KEY (`POST_ID`),
    CONSTRAINT `FK_POST_USER` FOREIGN KEY (`USER_ID`) REFERENCES `USER` (`ID`) ON UPDATE CASCADE ON DELETE RESTRICT,
    INDEX `IDX_POST_USER` (`USER_ID`),
    INDEX `IDX_POST_VISIBLE_CREATED` (`IS_BLOCK`, `IS_USER_WITHDRAWN`, `CREATE_AT`)
) ENGINE=INNODB DEFAULT CHARSET=UTF8MB4 COLLATE=UTF8MB4_UNICODE_CI COMMENT='게시글';

CREATE TABLE `POST_LIKE` (
    `POST_LIKE_ID` BIGINT NOT NULL AUTO_INCREMENT,
    `POST_ID` BIGINT NOT NULL,
    `USER_ID` BIGINT NOT NULL,
    `CREATE_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (`POST_LIKE_ID`),
    CONSTRAINT `UK_POST_LIKE_POST_USER` UNIQUE (`POST_ID`, `USER_ID`),
    CONSTRAINT `FK_POST_LIKE_POST` FOREIGN KEY (`POST_ID`) REFERENCES `POST` (`POST_ID`) ON DELETE CASCADE,
    CONSTRAINT `FK_POST_LIKE_USER` FOREIGN KEY (`USER_ID`) REFERENCES `USER` (`ID`) ON DELETE RESTRICT,
    INDEX `IDX_POST_LIKE_USER` (`USER_ID`)
) ENGINE=INNODB DEFAULT CHARSET=UTF8MB4 COLLATE=UTF8MB4_UNICODE_CI;

CREATE TABLE `IMAGE_UPLOAD` (
    `UPLOAD_ID` BIGINT NOT NULL AUTO_INCREMENT,
    `ORIGIN_NAME` VARCHAR(255) NOT NULL,
    `UPLOAD_PATH` VARCHAR(500) NOT NULL,
