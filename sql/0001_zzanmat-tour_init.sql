    CONSTRAINT `FK_POST_UPLOAD_POST` FOREIGN KEY (`POST_ID`) REFERENCES `POST` (`POST_ID`) ON DELETE CASCADE,
    CONSTRAINT `FK_POST_UPLOAD_UPLOAD` FOREIGN KEY (`UPLOAD_ID`) REFERENCES `IMAGE_UPLOAD` (`UPLOAD_ID`) ON DELETE CASCADE,
