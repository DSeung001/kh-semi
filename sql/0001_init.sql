-- 팔로우 -- 
CREATE TABLE IF NOT EXISTS FOLLOWE(
	FOLLOWE_ID BIGINT primary KEY,
    FOLLOWER_ID BIGINT NOT NULL,
    FOLLOWERING_ID BIGINT NOT NULL,
    
    CONSTRAINT uk_follower_following UNIQUE (follower_id, FOLLOWERING_ID),
    
    -- 외래키 설정 (기존과 동일하게 유지 가능)
    FOREIGN KEY (follower_id) REFERENCES user(ID) ON DELETE CASCADE,
    FOREIGN KEY (FOLLOWERING_ID) REFERENCES user(ID) ON DELETE CASCADE
);

