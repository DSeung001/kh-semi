-- 미션 --
CREATE TABLE IF NOT EXISTS MISSION(
	MISSION_ID BIGINT primary KEY,
    MISSION_CONTENT TEXT NOT NULL,
    MISSION_CONDITION INT NOT NULL,
    MISSION_CATEGORY VARCHAR(50) NOT NULL,
    MISSION_CREATE_AT DATETIME NOT NULL
);

-- 미션 진행도 --
CREATE TABLE IF NOT EXISTS MISSION_PROGRESS(
	MISSION_PROGRESS_ID BIGINT PRIMARY KEY,
    ID BIGINT NOT NULL,
    MISSION_ID BIGINT NOT NULL,
    PROGRESS smallint unsigned,
    CREATE_AT DATETIME NOT NULL,
    UPDATE_AT DATETIME NOT NULL,
    IS_DONE BOOL
);

ALTER TABLE MISSION_PROGRESS 
